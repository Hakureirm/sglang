# (2026-07-07): if the rwkv7_backend.py is_target_verify addition that
# Strategy B depends on turns out to hit a wall, this is a complete alternate
# design that needs ZERO backend changes (it never sets ForwardMode.
# TARGET_VERIFY at all — it runs the target through an ordinary EXTEND forward
# and manually snapshots/restores around it, at the cost of a second forward
# pass to re-commit the accepted prefix whenever acceptance is partial).
#
# NOT wired into forward_batch_generation above and NOT maintained — its
# _draft_extend/_run_extend/_build_forward call signatures below predate the
# `batch` threading Strategy B needed and would need re-threading to run again.
# See project-spec-decode.md (memory) for the full Strategy A/B trade-off.
